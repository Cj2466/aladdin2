def test_breakeven_is_reported_for_a_spec_whose_gross_is_positive_but_net_is_not():
    """REGRESSION GUARD for a real defect found by the independent
    verification pass: the breakeven line used to be gated on the NET Sharpe
    being positive, which suppressed it for precisely the specs where it is
    the whole point — a strong gross signal whose cost makes it unharvestable.
    That silently deleted this family's most interesting finding from its own
    report. The gate is on the GROSS result now."""
    # gross cumulative = -2.51 + 5.86 = +3.35 -> breakeven 10bp * 3.35/5.86
    uneconomic = _result("ofi_ortho_h1", net=-1.05, gross=1.40, cum=-2.5127, drag=5.8569)
    text = _summary_with([uneconomic])

    assert "breakeven ~5.7bp one-way" in text, text
    assert "STRONG SIGNAL THAT CANNOT PAY THE FEE" in text
    assert f"{BINANCE_TAKER_FEE_BPS:.0f}bp" in text


def test_a_spec_that_loses_money_gross_gets_no_breakeven_line():
    """The other side of the same gate: a breakeven cost is meaningless when
    there is no gross profit to spend, so it must not be invented."""
    text = _summary_with([_result("ofi_x", net=-2.0, gross=-1.5, cum=-3.0, drag=1.0)])

    # "breakevens below" appears in the standing COSTS preamble; what must be
    # absent is a computed per-spec breakeven for THIS spec.
    assert "breakeven ~" not in text
    assert "CANNOT PAY THE FEE" not in text


def test_the_published_binance_taker_fee_is_recorded_as_the_floor_not_the_charge():
    """The specs are charged OFI_COST_BPS, deliberately above the exchange's
    headline taker fee. The fee constant exists only to give the breakeven a
    floor to be compared against, and must never quietly become the charge."""
    assert BINANCE_TAKER_FEE_BPS == 5.0
    assert OFI_COST_BPS == 10.0
    assert OFI_COST_BPS > BINANCE_TAKER_FEE_BPS

def test_orthogonalized_signal_ignores_all_future_data():
    """The expanding-window estimator's whole purpose. Overwrite EVERY panel
    row after a chosen formation with garbage — prices, both signed volume
    halves — and the signal at that formation must be bit-identical, for the
    raw and the orthogonalized variant alike."""
    # 900 days so the weekly grid has ~128 points: the standardization needs
    # 30 and the expanding regression 30 more, so an orthogonalized signal
    # does not exist before grid point ~59. Choosing a formation inside the
    # warm-up would make this test compare NaN to NaN and pass vacuously.
    panels = _build_world(flow_carries_genuine_info=True, n_days=900)
    horizon = 7
    before = build_ofi_signals(panels, horizon)

    rows = formation_grid(panels.close.index, horizon)
    k = len(rows) * 3 // 4
    cut = rows[k]
    assert before.ortho.iloc[k].notna().any(), (
        "fixture chose a formation inside the signal warm-up — nothing to compare"
    )

    rng = np.random.default_rng(7)
    mutated = OfiPanels(
        close=panels.close.copy(),
        quote_volume=panels.quote_volume.copy(),
        buy_quote=panels.buy_quote.copy(),
        sell_quote=panels.sell_quote.copy(),
        trade_count=panels.trade_count.copy(),
        coverage={},
        symbols_missing=[],
    )
    tail = slice(cut + 1, None)
    shape = mutated.close.iloc[tail].shape
    mutated.close.iloc[tail] = rng.uniform(1.0, 500.0, shape)
    mutated.buy_quote.iloc[tail] = rng.uniform(1e6, 9e8, shape)
    mutated.sell_quote.iloc[tail] = rng.uniform(1e6, 9e8, shape)

    after = build_ofi_signals(mutated, horizon)

    for name, b, a in (
        ("raw", before.raw, after.raw),
        ("ortho", before.ortho, after.ortho),
        ("period_return", before.period_return, after.period_return),
    ):
        pd.testing.assert_series_equal(
            b.iloc[k], a.iloc[k], check_names=False,
            obj=f"{name} signal at formation {before.raw.index[k].date()}",
        )
        # and every earlier formation too, not just the boundary one
        pd.testing.assert_frame_equal(
            b.iloc[: k + 1], a.iloc[: k + 1], obj=f"{name} signals up to the formation"
        )

    assert not before.ortho.iloc[k].isna().all(), "fixture produced an all-NaN signal to compare"


def test_mutating_the_formation_row_itself_does_change_the_signal():
    """The other half of the look-ahead test: data AT the formation is known
    and must be used. Without this, a signal that ignored everything would
    pass the test above."""
    panels = _build_world(flow_carries_genuine_info=True, n_days=900)
    horizon = 7
    before = build_ofi_signals(panels, horizon)
    rows = formation_grid(panels.close.index, horizon)
    k = len(rows) * 3 // 4
    assert before.raw.iloc[k].notna().any(), "fixture chose a formation inside the warm-up"

    mutated = OfiPanels(
        close=panels.close.copy(),
        quote_volume=panels.quote_volume.copy(),
        buy_quote=panels.buy_quote.copy(),
        sell_quote=panels.sell_quote.copy(),
        trade_count=panels.trade_count.copy(),
        coverage={},
        symbols_missing=[],
    )
    mutated.buy_quote.iloc[rows[k]] *= 5.0

    after = build_ofi_signals(mutated, horizon)
    assert not np.allclose(
        before.raw.iloc[k].to_numpy(), after.raw.iloc[k].to_numpy(), equal_nan=True
    ), "formation-row flow is settled, known data and must move the signal"


def test_expanding_orthogonalize_coefficients_use_only_past_and_present():
    """Unit-level companion to the panel test: the residual at t equals the
    residual of an OLS fitted by hand on rows 0..t ONLY."""
    rng = np.random.default_rng(11)
    n = 200
    x = pd.DataFrame({"A": rng.normal(size=n)})
    y = pd.DataFrame({"A": 3.0 + 2.0 * x["A"] + rng.normal(0.0, 0.5, n)})

    out = expanding_orthogonalize(y, x, min_obs=MIN_ORTHO_REGRESSION_OBS)

    for t in (MIN_ORTHO_REGRESSION_OBS - 1, 60, 150, n - 1):
        xs = x["A"].to_numpy()[: t + 1]
        ys = y["A"].to_numpy()[: t + 1]
        beta_hat, alpha_hat = np.polyfit(xs, ys, 1)
        expected = ys[-1] - alpha_hat - beta_hat * xs[-1]
        assert out["A"].iloc[t] == pytest.approx(expected, rel=1e-9, abs=1e-12), (
            f"residual at t={t} does not match a hand-fitted OLS on rows 0..{t}"
        )

    assert out["A"].iloc[: MIN_ORTHO_REGRESSION_OBS - 1].isna().all(), (
        "residuals must be NaN before min_obs pairs exist"
    )


def test_perfectly_explained_signal_orthogonalizes_to_zero():
    """If order flow IS an exact affine function of the same-period return,
    there is by construction nothing left after projecting the return out."""
    rng = np.random.default_rng(3)
    x = pd.DataFrame({"A": rng.normal(size=150)})
    y = pd.DataFrame({"A": -7.0 + 4.0 * x["A"]})

    out = expanding_orthogonalize(y, x).dropna()
    assert len(out) > 100
    assert float(out["A"].abs().max()) < 1e-9


def test_orthogonalize_skips_ragged_history_without_injecting_zeros():
    """A coin listed late must not have its pre-listing NaNs counted as
    (0, 0) observations in its own expanding regression."""
    rng = np.random.default_rng(5)
    n = 200
    x = pd.DataFrame({"A": rng.normal(size=n)})
    y = pd.DataFrame({"A": 1.0 + 2.0 * x["A"] + rng.normal(0.0, 0.3, n)})
    x_ragged, y_ragged = x.copy(), y.copy()
    x_ragged.iloc[:50] = np.nan
    y_ragged.iloc[:50] = np.nan

    out = expanding_orthogonalize(y_ragged, x_ragged)

    assert out["A"].iloc[:50].isna().all()
    # first defined residual arrives min_obs valid pairs after the listing
    first_valid = int(out["A"].notna().to_numpy().argmax())
    assert first_valid == 50 + MIN_ORTHO_REGRESSION_OBS - 1

    xs = x_ragged["A"].to_numpy()[50 : first_valid + 1]
    ys = y_ragged["A"].to_numpy()[50 : first_valid + 1]
    beta_hat, alpha_hat = np.polyfit(xs, ys, 1)
    assert out["A"].iloc[first_valid] == pytest.approx(
        ys[-1] - alpha_hat - beta_hat * xs[-1], rel=1e-9
    )



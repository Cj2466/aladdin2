def test_weekly_signal_aggregates_the_whole_week_not_just_the_last_day():
    """The horizon-7 flow is the log ratio of the week's SUMMED halves. A
    week whose days individually look balanced but whose totals do not must
    produce a non-zero flow."""
    index = pd.date_range("2020-01-01", periods=30, freq="D")
    buy = pd.DataFrame(100.0, index=index, columns=["A"])
    sell = pd.DataFrame(100.0, index=index, columns=["A"])
    buy.iloc[8:15] = 300.0  # one lopsided week
    close = pd.DataFrame(100.0, index=index, columns=["A"])
    panels = OfiPanels(
        close=close,
        quote_volume=pd.DataFrame(1e9, index=index, columns=["A"]),
        buy_quote=buy,
        sell_quote=sell,
        trade_count=pd.DataFrame(1.0, index=index, columns=["A"]),
        coverage={},
        symbols_missing=[],
    )
    signals = build_ofi_signals(panels, 7)
    rows = formation_grid(index, 7)
    at_14 = rows.index(14)
    of_expected = math.log(300.0 * 7) - math.log(100.0 * 7)
    # standardization is applied on top, so check the pre-standardized ratio
    week_buy = buy["A"].iloc[8:15].sum()
    week_sell = sell["A"].iloc[8:15].sum()
    assert math.log(week_buy) - math.log(week_sell) == pytest.approx(of_expected)
    assert signals.period_return.index[at_14] == index[14]



def test_standardization_is_scale_only_not_a_z_score():
    """Equation (1.2) divides by sigma and does NOT subtract a mean. A
    z-score implementation would zero out a constant-mean series' level;
    this one must preserve it, sign included."""
    n = 60
    of = pd.DataFrame({"A": [5.0 + (1.0 if i % 2 else -1.0) for i in range(n)]})

    out = standardize_order_flow(of, window=OFI_STANDARDIZATION_WINDOW)

    sigma = float(of["A"].iloc[:OFI_STANDARDIZATION_WINDOW].std())
    at_first = out["A"].iloc[OFI_STANDARDIZATION_WINDOW - 1]
    assert at_first == pytest.approx(of["A"].iloc[OFI_STANDARDIZATION_WINDOW - 1] / sigma)
    assert at_first > 0.0, "a positive flow must stay positive — demeaning would flip signs"
    assert out["A"].iloc[: OFI_STANDARDIZATION_WINDOW - 1].isna().all()

    demeaned = (of - of.rolling(OFI_STANDARDIZATION_WINDOW).mean()) / of.rolling(
        OFI_STANDARDIZATION_WINDOW
    ).std()
    assert not np.isclose(at_first, demeaned["A"].iloc[OFI_STANDARDIZATION_WINDOW - 1])


def test_standardization_window_is_inclusive_of_the_current_observation():
    """sigma(of_{t-29:t}) is 30 observations ENDING AT t, so the first
    defined value is at row 29, not row 30."""
    of = pd.DataFrame({"A": np.arange(1.0, 41.0)})
    out = standardize_order_flow(of, window=OFI_STANDARDIZATION_WINDOW)
    assert pd.isna(out["A"].iloc[OFI_STANDARDIZATION_WINDOW - 2])
    assert pd.notna(out["A"].iloc[OFI_STANDARDIZATION_WINDOW - 1])


def test_degenerate_sigma_yields_nan_not_infinity():
    of = pd.DataFrame({"A": [2.0] * 40})
    out = standardize_order_flow(of, window=OFI_STANDARDIZATION_WINDOW)
    assert out["A"].isna().all(), "a constant flow has sigma 0 — the ratio must not be inf"



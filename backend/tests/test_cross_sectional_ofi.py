SYMBOLS = [f"C{i:02d}USDT" for i in range(40)]


# --- synthetic-world construction -------------------------------------------


def _panels_from_flows(
    order_flow: pd.DataFrame,
    close: pd.DataFrame,
    total_quote: float = 1e9,
) -> OfiPanels:
    """Inverts the source's flow definition to build a panel that HAS a
    prescribed order flow: given a target of = log(buy) - log(sell) and a
    total turnover V, buy = V*e^of/(1+e^of) and sell = V/(1+e^of). So the
    test controls the economics directly and still exercises the real
    log-difference code path rather than injecting a signal behind it."""
    ratio = np.exp(order_flow)
    buy = total_quote * ratio / (1.0 + ratio)
    sell = total_quote / (1.0 + ratio)
    volume = pd.DataFrame(total_quote, index=close.index, columns=close.columns)
    return OfiPanels(
        close=close,
        quote_volume=volume,
        buy_quote=buy,
        sell_quote=sell,
        trade_count=pd.DataFrame(10_000.0, index=close.index, columns=close.columns),
        coverage={},
        symbols_missing=[],
    )


def _build_world(
    *,
    flow_carries_genuine_info: bool,
    n_days: int = 900,
    seed: int = 20260829,
) -> OfiPanels:
    """Two worlds from one generator, differing only in `flow_carries_genuine_info`.

    In BOTH worlds returns mean-revert hard (r_{t+1} has a -0.6 loading on
    r_t: strong short-term reversal) and order flow is dominated by a term
    proportional to the SAME-period return, which is exactly the
    contamination the source's footnote-12 orthogonalization exists to
    remove.

    The ONLY difference: when flow_carries_genuine_info is True, order flow
    also contains an independent component g that genuinely predicts the
    next period's return with a POSITIVE sign — the source's "permanent
    effect". When False, g is pure noise that predicts nothing, so every
    bit of predictive content in the raw flow is the reversal term."""
    rng = np.random.default_rng(seed)
    index = pd.date_range("2020-01-01", periods=n_days, freq="D")
    shape = (n_days, len(SYMBOLS))

    g = rng.normal(0.0, 1.0, shape)  # the independent "permanent" component
    shock = rng.normal(0.0, 0.03, shape)

    r = np.zeros(shape)
    r[0] = shock[0]
    for t in range(1, n_days):
        r[t] = -0.6 * r[t - 1] + shock[t]
        if flow_carries_genuine_info:
            r[t] += 0.05 * g[t - 1]

    # Order flow is dominated by the same-period return (the transitory,
    # reversal-correlated part) plus the independent component.
    of = 40.0 * r + 1.5 * g

    close = pd.DataFrame(
        100.0 * np.cumprod(1.0 + r, axis=0), index=index, columns=SYMBOLS
    )
    return _panels_from_flows(
        pd.DataFrame(of, index=index, columns=SYMBOLS), close
    )


def _sharpe_of(panels: OfiPanels, variant: str, horizon: int = 1) -> float:
    spec = OfiSpec(
        pattern_id=f"t_{variant}_h{horizon}", signal_variant=variant, horizon_days=horizon
    )
    config = OfiConfig(cost_bps=0.0, formation_start=date(2020, 1, 1))
    bt = run_ofi_backtest(panels, spec, config)
    assert len(bt.daily_returns) > 200, "synthetic replay produced too few days to judge"
    return sharpe_ratio(bt.daily_returns, periods_per_year=365.0)


# --- THE central pair --------------------------------------------------------


def test_orthogonalization_kills_a_pure_reversal_signal():
    """World where order flow carries NO independent information: all of
    its apparent predictive power is the same-period return, i.e. short-term
    reversal. The RAW flow must therefore look strongly predictive (with the
    sign reversal implies — high flow means a high past return means a LOW
    next return, so a long-high-flow book loses badly), and orthogonalizing
    must collapse that to nothing."""
    panels = _build_world(flow_carries_genuine_info=False)

    raw = _sharpe_of(panels, "raw")
    ortho = _sharpe_of(panels, "ortho")

    assert raw < -2.0, (
        f"raw flow should inherit the reversal effect strongly, got Sharpe {raw:.3f} — "
        "the fixture is not producing the contamination the test is about"
    )
    assert abs(ortho) < 0.75, (
        f"orthogonalized flow should retain NOTHING in a world where flow carries no "
        f"independent information, but scored Sharpe {ortho:.3f}"
    )
    assert abs(ortho) < abs(raw) / 3.0, (
        f"orthogonalization barely dented the reversal signal: |{ortho:.3f}| vs |{raw:.3f}|"
    )


def test_orthogonalization_preserves_a_genuine_order_flow_signal():
    """Same generator, same reversal contamination, same magnitudes — the
    one change is that order flow now also carries an independent component
    that really does predict the next period. The orthogonalized signal must
    survive and must BEAT the raw one, because the raw one is still dragged
    the wrong way by the reversal term it never removed."""
    panels = _build_world(flow_carries_genuine_info=True)

    raw = _sharpe_of(panels, "raw")
    ortho = _sharpe_of(panels, "ortho")

    assert ortho > 2.0, (
        f"a genuine order-flow effect must survive orthogonalization, got Sharpe {ortho:.3f}"
    )
    assert ortho > raw, (
        f"orthogonalized ({ortho:.3f}) should beat raw ({raw:.3f}) when the raw signal is "
        "still contaminated by a reversal term pointing the other way"
    )


def test_the_two_worlds_differ_only_in_the_genuine_component():
    """Guards the pair above from a fixture bug: the two worlds must share
    an identical reversal structure, so the difference in the orthogonalized
    result cannot come from anything else. The RAW Sharpe stays strongly
    negative in both (same contamination); only the ORTHO Sharpe moves."""
    no_info = _build_world(flow_carries_genuine_info=False)
    with_info = _build_world(flow_carries_genuine_info=True)

    assert _sharpe_of(no_info, "raw") < -2.0
    assert _sharpe_of(with_info, "raw") < -2.0
    assert _sharpe_of(no_info, "ortho") < 0.75 < _sharpe_of(with_info, "ortho")



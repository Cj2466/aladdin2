def test_costs_reduce_the_net_sharpe_and_are_charged_once_per_formation():
    panels = _build_world(flow_carries_genuine_info=True, n_days=600)
    spec = OfiSpec(pattern_id="t", signal_variant="ortho", horizon_days=7)

    free = run_ofi_backtest(panels, spec, OfiConfig(cost_bps=0.0, formation_start=date(2020, 1, 1)))
    charged = run_ofi_backtest(
        panels, spec, OfiConfig(cost_bps=10.0, formation_start=date(2020, 1, 1))
    )

    assert free.total_cost_drag == 0.0
